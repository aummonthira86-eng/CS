function seedFaqs(): Faq[] {
  const base = new Date("2026-09-01T09:00:00+07:00").getTime();
  return rows.map(([id, q, cat, kw, a, status], i) => {
    const created = new Date(base + i * 36e5 * 7).toISOString();
    return {
      faq_id: id,
      question: q,
      answer: a,
      category_id: cat,
      keywords: kw,
      status: status ?? "published",
      created_at: created,
      updated_at: created,
    };
  });
}

export function seedState(): DataState {
  return {
    faqs: seedFaqs(),
    categories: cats.map((c) => ({ ...c })),
    settings: { ...defaultSettings },
  };
}
